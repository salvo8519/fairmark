@posix_only
def test_a_missing_tool_never_blocks(
    project: Path, tmp_path_factory: pytest.TempPathFactory
) -> None:
    """A rustup component that is not installed, and no ruff, mypy or uv at all."""
    bin_dir = tmp_path_factory.mktemp("bin")
    for tool in ("cargo", "rustfmt"):
        fake = bin_dir / tool
        fake.write_text("#!/bin/sh\necho 'component not installed' >&2\nexit 1\n", encoding="utf-8")
        fake.chmod(0o755)
    (bin_dir / "git").symlink_to(shutil.which("git") or "/usr/bin/git")
    (project / "crates" / "demo" / "src" / "lib.rs").write_text("pub fn  f(){}\n", encoding="utf-8")
    (project / "scripts" / "tool.py").write_text("import os\n", encoding="utf-8")
    result = subprocess.run(
        [sys.executable, str(project / ".claude" / "hooks" / "quality_gate.py")],
        input=json.dumps({"session_id": "s1"}),
        capture_output=True,
        text=True,
        encoding="utf-8",
        env={**os.environ, "CLAUDE_PROJECT_DIR": str(project), "PATH": str(bin_dir)},
        cwd=project,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    message = system_message(result)
    assert "rustfmt --check: tool not found" in message
    assert "cargo clippy -p demo: tool not found" in message
    assert "ruff check: tool not found" in message


@needs_tools
def test_a_staged_rename_and_a_non_ascii_name_are_checked(project: Path) -> None:
    git(project, "mv", "scripts/tool.py", "scripts/renamed.py")
    (project / "scripts" / "renamed.py").write_text("import os\n", encoding="utf-8")
    git(project, "add", "-A")
    (project / "scripts" / "résumé.py").write_text("import sys\n", encoding="utf-8")
    result = run(project)
    assert result.returncode == 2
    # The linters print paths with the platform's separator (a backslash on Windows).
    findings = result.stderr.replace("\\", "/")
    assert "scripts/renamed.py" in findings
    assert "scripts/résumé.py" in findings


