def test_the_hook_runs_when_the_session_and_a_subagent_stop() -> None:
    settings = json.loads((ROOT / ".claude" / "settings.json").read_text(encoding="utf-8"))
    for event in ("Stop", "SubagentStop"):
        commands = [h for group in settings["hooks"][event] for h in group["hooks"]]
        gate = [h for h in commands if h["command"].endswith("/.claude/hooks/quality-gate.sh")]
        assert len(gate) == 1, event
        assert gate[0]["timeout"] > 60  # longer than the budget of the checks


def load_gate() -> Any:
    spec = importlib.util.spec_from_file_location("quality_gate", HOOKS / "quality_gate.py")
    module = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


@pytest.mark.parametrize(
    ("value", "expected"),
    [("30", 30.0), ("300", 75.0), ("inf", 60.0), ("nan", 60.0), ("-1", 60.0), ("soon", 60.0)],
)
def test_the_budget_is_finite_and_below_the_hook_timeout(
    value: str, expected: float, monkeypatch: pytest.MonkeyPatch
) -> None:
    gate = load_gate()
    monkeypatch.setenv("FAIRMARK_QUALITY_BUDGET", value)
    assert gate.budget_from_env() == expected
    settings = json.loads((ROOT / ".claude" / "settings.json").read_text(encoding="utf-8"))
    timeouts = [
        h["timeout"]
        for event in ("Stop", "SubagentStop")
        for entry in settings["hooks"][event]
        for h in entry["hooks"]
        if h["command"].endswith("quality-gate.sh")
    ]
    assert timeouts and all(t > gate.MAX_BUDGET for t in timeouts)


def test_tools_never_install_and_clippy_never_rewrites_the_lock(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    gate = load_gate()
    monkeypatch.setattr(gate.shutil, "which", lambda name, path=None: None if path else name)
    assert gate.python_tool(tmp_path, "ruff") == ["ruff"]
    monkeypatch.setattr(
        gate.shutil, "which", lambda name, path=None: "uv" if name == "uv" and not path else None
    )
    assert gate.python_tool(tmp_path, "ruff") == ["uv", "run", "--no-sync", "--quiet", "ruff"]
    monkeypatch.setattr(gate.shutil, "which", lambda name, path=None: name)
    monkeypatch.setattr(gate, "works", lambda command, root, deadline: True)
    monkeypatch.setattr(gate, "crate_of", lambda root, path: "demo")
    monkeypatch.setattr(gate, "rust_edition", lambda root: "2021")
    checks = dict(gate.plan(tmp_path, ["crates/demo/src/lib.rs"], 0.0))
    clippy = checks["cargo clippy -p demo"]
    assert clippy is not None and "--locked" in clippy


def test_a_probe_never_outlives_the_deadline(tmp_path: Path) -> None:
    gate = load_gate()
    assert gate.works([sys.executable, "-c", "pass"], tmp_path, time.monotonic() - 1) is False
    assert gate.works([sys.executable, "-c", "pass"], tmp_path, time.monotonic() + 10) is True


def test_subagents_and_the_main_session_keep_separate_blocks() -> None:
    gate = load_gate()
    main = gate.state_key({"session_id": "s1", "hook_event_name": "Stop"})
    sub = gate.state_key({"session_id": "s1", "hook_event_name": "SubagentStop", "agent_id": "a1"})
    other = gate.state_key(
        {"session_id": "s1", "hook_event_name": "SubagentStop", "agent_id": "a2"}
    )
    assert len({main, sub, other}) == 3
    assert gate.state_key("not a payload") == "default"
