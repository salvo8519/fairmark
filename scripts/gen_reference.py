"""Generate docs/reference/methods.md from the engine registry and JSON Schemas.

Run after adding or changing a method. CI fails if the committed page is stale:
    python scripts/gen_reference.py --check
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import fairmark as fm

OUT = Path(__file__).resolve().parents[1] / "docs" / "reference" / "methods.md"


def field_type(spec: dict) -> str:
    if "enum" in spec:
        return " \\| ".join(f"`{v}`" for v in spec["enum"])
    t = spec.get("type", "")
    if spec.get("pattern", "").startswith("^-?\\d"):
        return "decimal"
    if t == "array":
        return f"list of {field_type(spec.get('items', {}))}"
    return t if isinstance(t, str) else " \\| ".join(t)


def render() -> str:
    lines = [
        "# Methods reference",
        "",
        "<!-- Generated by scripts/gen_reference.py from the engine registry. Do not edit. -->",
        "",
        "Every method is available with the same id and inputs from Python (`fm.run`), the CLI",
        "(`fairmark run`), MCP and function calling (tool name `fairmark_<id with underscores>`).",
        "Decimals may be passed as JSON numbers or strings and are returned as strings.",
        "",
    ]
    for m in fm.methods():
        schema = fm.tools._inline(fm.input_schema(m["id"]))
        required = set(schema.get("required", []))
        lines += [
            f"## `{m['id']}`",
            "",
            f"**{m['title']}** · method version {m['version']} · tool "
            f"`{fm.tools.tool_name(m['id'])}`",
            "",
            m["description"],
            "",
            "| Input | Type | Required | Default | Description |",
            "| --- | --- | :---: | --- | --- |",
        ]
        for name, spec in schema["properties"].items():
            default = f"`{json.dumps(spec['default'])}`" if "default" in spec else ""
            desc = spec.get("description", "").replace("\n", " ")
            req = "yes" if name in required else "no"
            lines.append(f"| `{name}` | {field_type(spec)} | {req} | {default} | {desc} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != content:
            sys.exit("docs/reference/methods.md is stale: run python scripts/gen_reference.py")
        return
    OUT.write_text(content)


if __name__ == "__main__":
    main()
