"""Generate the methods reference (English and Italian) from the engine registry.

    python scripts/gen_reference.py           # write docs/<lang>/reference/methods.md
    python scripts/gen_reference.py --check   # fail if any is stale (CI)

Field descriptions come from the Rust doc comments (English) in both editions.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import fairmark as fm

ROOT = Path(__file__).resolve().parents[1]

TEXT = {
    "en": {
        "title": "Methods reference",
        "intro": [
            "Every method is available with the same id and inputs from Python (`fm.run`),",
            "the CLI (`fairmark run`), MCP and function calling",
            "(tool name `fairmark_<id with underscores>`).",
            "Decimals may be passed as JSON numbers or strings and are returned as strings.",
        ],
        "version": "method version",
        "tool": "tool",
        "header": "| Input | Type | Required | Default | Description |",
        "yes": "yes",
        "no": "no",
        "decimal": "decimal",
        "list": "list of",
    },
    "it": {
        "title": "Riferimento dei metodi",
        "intro": [
            "Ogni metodo è disponibile con lo stesso identificativo e gli stessi input da Python",
            "(`fm.run`), dalla CLI (`fairmark run`), via MCP e function calling (nome del tool",
            "`fairmark_<id con underscore>`). I decimali si passano come numeri JSON o stringhe e",
            "sono restituiti come stringhe. Le descrizioni dei campi provengono dal codice",
            "sorgente e sono in inglese.",
        ],
        "version": "versione del metodo",
        "tool": "tool",
        "header": "| Input | Tipo | Obbligatorio | Default | Descrizione |",
        "yes": "sì",
        "no": "no",
        "decimal": "decimale",
        "list": "lista di",
    },
}


def field_type(spec: dict[str, Any], t: dict[str, Any]) -> str:
    if "enum" in spec:
        return " \\| ".join(f"`{v}`" for v in spec["enum"])
    kind = spec.get("type", "")
    if spec.get("pattern", "").startswith("^-?\\d"):
        return str(t["decimal"])
    if kind == "array":
        return f"{t['list']} {field_type(spec.get('items', {}), t)}"
    return kind if isinstance(kind, str) else " \\| ".join(kind)


def render(lang: str) -> str:
    t = TEXT[lang]
    lines = [
        f"# {t['title']}",
        "",
        "<!-- Generated by scripts/gen_reference.py from the engine registry. Do not edit. -->",
        "",
        *t["intro"],
        "",
    ]
    for m in fm.methods():
        schema = fm.tools._inline(fm.input_schema(m["id"]))
        required = set(schema.get("required", []))
        lines += [
            f"## `{m['id']}`",
            "",
            f"**{m['title']}** · {t['version']} {m['version']} · {t['tool']} "
            f"`{fm.tools.tool_name(m['id'])}`",
            "",
            m["description"],
            "",
            str(t["header"]),
            "| --- | --- | --- | --- | --- |",
        ]
        for name, spec in schema["properties"].items():
            default = f"`{json.dumps(spec['default'])}`" if "default" in spec else ""
            desc = spec.get("description", "").replace("\n", " ")
            req = t["yes"] if name in required else t["no"]
            lines.append(f"| `{name}` | {field_type(spec, t)} | {req} | {default} | {desc} |")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for lang in TEXT:
        out = ROOT / "docs" / lang / "reference" / "methods.md"
        content = render(lang)
        if args.check:
            if not out.exists() or out.read_text() != content:
                stale.append(str(out.relative_to(ROOT)))
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(content)
    if stale:
        sys.exit(f"Stale generated reference: {stale}. Run: uv run just generate")


if __name__ == "__main__":
    main()
