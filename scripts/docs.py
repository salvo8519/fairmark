"""Build the bilingual documentation (English source, Italian edition).

Zensical builds one language per site, so each language is a separate site sharing the same
assets: English at the site root, Italian under /it/, linked by the language selector.

    python scripts/docs.py build           # both sites into site/ and site/it/ (strict)
    python scripts/docs.py serve --lang it # live preview of one language
    python scripts/docs.py prepare         # copy shared assets, generate zensical.it.toml
"""

from __future__ import annotations

import argparse
import copy
import fnmatch
import shutil
import subprocess
from pathlib import Path
from typing import Any

import tomli_w
import tomllib
import yaml

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
SHARED = DOCS / "_shared"
LANGS = ["en", "it"]


def copy_shared() -> None:
    for lang in LANGS:
        for item in SHARED.iterdir():
            target = DOCS / lang / item.name
            if target.exists():
                shutil.rmtree(target) if target.is_dir() else target.unlink()
            if item.is_dir():
                shutil.copytree(item, target)
            else:
                shutil.copy2(item, target)


def translate_nav(nav: list[Any], cfg: dict[str, Any], en_site: str) -> list[Any]:
    out: list[Any] = []
    for entry in nav:
        for title, value in entry.items():
            label = cfg["sections"].get(title, title)
            if isinstance(value, list):
                children = translate_nav(value, cfg, en_site)
                if children:
                    out.append({label: children})
            else:
                page = value
                if any(fnmatch.fnmatch(page, p) for p in cfg["english_only"]):
                    url = en_site + page.removesuffix(".md") + "/"
                    out.append({f"{h1(DOCS / 'en' / page)} (English)": url})
                elif (DOCS / "it" / page).exists():
                    out.append({label: page})
    return out


def h1(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.stem.replace("-", " ").capitalize()


def flatten(nav: list[Any]) -> list[Any]:
    """Zensical nav entries: plain page paths where possible."""
    out: list[Any] = []
    for entry in nav:
        for title, value in entry.items():
            if isinstance(value, list):
                out.append({title: flatten(value)})
            elif title in ("Home",) or value.startswith("http"):
                out.append({title: value})
            else:
                out.append(value)
    return out


def italian_config() -> None:
    base = tomllib.loads((ROOT / "zensical.toml").read_text())
    cfg = yaml.safe_load((ROOT / "i18n/it.yaml").read_text())
    it = copy.deepcopy(base)
    p = it["project"]
    en_site = base["project"]["site_url"]
    p["site_url"] = en_site + "it/"
    p["site_description"] = cfg["site_description"]
    p["docs_dir"] = "docs/it"
    p["site_dir"] = "site/it"
    p["edit_uri"] = "edit/main/docs/it/"
    p["theme"]["language"] = "it"
    nav = flatten(translate_nav(_normalise(base["project"]["nav"]), cfg, en_site))
    del p["nav"]
    header = "# GENERATED by scripts/docs.py from zensical.toml and i18n/it.yaml. Do not edit.\n\n"
    body = tomli_w.dumps(it)
    marker = "\n[project."
    cut = body.index(marker)
    nav_toml = "nav = " + toml_inline(nav, 0) + "\n"
    (ROOT / "zensical.it.toml").write_text(header + body[:cut] + "\n" + nav_toml + body[cut:])


def toml_inline(value: Any, indent: int) -> str:
    """Serialise the nav as TOML inline arrays/tables (mixed arrays allowed by TOML 1.0)."""
    pad = "  " * (indent + 1)
    if isinstance(value, str):
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(value, dict):
        ((k, v),) = value.items()
        return "{ " + toml_inline(k, indent) + " = " + toml_inline(v, indent) + " }"
    items = ",\n".join(pad + toml_inline(v, indent + 1) for v in value)
    return "[\n" + items + ",\n" + "  " * indent + "]"


def _normalise(nav: list[Any]) -> list[Any]:
    out: list[Any] = []
    for entry in nav:
        if isinstance(entry, str):
            out.append({entry: entry})
        else:
            for title, value in entry.items():
                out.append({title: _normalise(value) if isinstance(value, list) else value})
    return out


def prepare() -> None:
    copy_shared()
    italian_config()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["prepare", "build", "serve"])
    parser.add_argument("--lang", choices=LANGS, default="en")
    args = parser.parse_args()
    prepare()
    configs = {"en": "zensical.toml", "it": "zensical.it.toml"}
    if args.command == "build":
        shutil.rmtree(ROOT / "site", ignore_errors=True)
        for lang in LANGS:
            subprocess.run(
                ["zensical", "build", "--strict", "-f", configs[lang]], cwd=ROOT, check=True
            )
    elif args.command == "serve":
        subprocess.run(["zensical", "serve", "-f", configs[args.lang]], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
