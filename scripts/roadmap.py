"""The roadmap as code: one file, checked offline, synchronised with GitHub.

`roadmap/roadmap.yaml` is the source of truth for the plan: milestones, epics and tasks, each
task linked to its GitHub issue and, when it has one, to its spec. GitHub is the source of
truth for the state of each issue (open or closed); `sync` copies that state into the file,
so the published roadmap page is generated offline, deterministically, from a reviewed file.

    python scripts/roadmap.py check [--pr-body FILE]  # offline: format, links, generated page
    python scripts/roadmap.py render                  # canonical file, regenerated page
    python scripts/roadmap.py sync [--write] [--apply-milestones]
        # online: compare with GitHub; --write updates statuses in the file;
        # --apply-milestones sets each issue's milestone on GitHub to the one in the file
    python scripts/roadmap.py list [--open] [--milestone M2]  # the plan, one task per line
    python scripts/roadmap.py new --milestone M2 --epic "Analysis" --title "..." \\
        [--labels area:core,parallel] [--spec 0008] [--body FILE]
        # create the issue on GitHub with its milestone and labels, and add it to the file

Rules checked by `check`: the file is in canonical form; issue numbers are unique; every task
has an issue; statuses are `open` or `done`; every spec folder in `specs/` is referenced by a
task, and every referenced spec exists; the roadmap page is generated from the file; with
`--pr-body`, the issue that the pull request closes is in the roadmap and its task is marked
`done` in the same change, so that GitHub and the file agree as soon as it is merged.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
ROADMAP = ROOT / "roadmap" / "roadmap.yaml"
PAGE = ROOT / "docs" / "en" / "project" / "roadmap.md"
SPECS = ROOT / "specs"
REPO = os.environ.get("GITHUB_REPOSITORY", "salvo8519/fairmark")
ISSUES_URL = f"https://github.com/{REPO}/issues"
SPECS_URL = f"https://github.com/{REPO}/tree/main/specs"
START, END = "<!-- roadmap:start (generated by scripts/roadmap.py) -->", "<!-- roadmap:end -->"
STATUSES = ("open", "done", "dropped")
TASK_KEYS = {"issue", "title", "tags", "status", "spec"}
EPIC_KEYS = {"title", "issue", "labels", "tasks"}
MILESTONE_KEYS = {"title", "gate", "release", "epics"}
SEMVER = re.compile(r"^\d+\.\d+\.\d+$")
HEADER = """\
# Source of truth for the plan: milestones, epics (parent issues) and tasks (sub-issues).
# The state of each issue lives on GitHub; `python scripts/roadmap.py sync --write` copies it
# here. Edit by hand or with `python scripts/roadmap.py new`; then `python scripts/roadmap.py
# render` rewrites this file canonically and regenerates docs/en/project/roadmap.md.
# Task tags: parallel = can be done independently; gfi = good first issue; maintainer =
# maintainer decision; needs-methodology = methodology to agree first.
"""


def q(text: str) -> str:
    """A YAML double-quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(text, ensure_ascii=False)


def load() -> dict[str, Any]:
    data = yaml.safe_load(ROADMAP.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        sys.exit("roadmap/roadmap.yaml: not a mapping")
    return data


def tasks(data: dict[str, Any]) -> list[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]:
    """(milestone, epic, task) for every task, in file order."""
    return [(m, e, t) for m in data["milestones"] for e in m["epics"] for t in e["tasks"]]


# ---- canonical file


def dump(data: dict[str, Any]) -> str:
    out = [HEADER, "labels:"]
    for label in data["labels"]:
        out.append(f"  - {{ name: {q(label['name'])}, color: {q(label['color'])} }}")
    out.append("")
    out.append("milestones:")
    for m in data["milestones"]:
        out.append(f"  - title: {q(m['title'])}")
        out.append(f"    gate: {q(m['gate'])}")
        out.append(f"    release: {q(m['release'])}")
        out.append("    epics:")
        for e in m["epics"]:
            out.append(f"      - title: {q(e['title'])}")
            if e.get("issue") is not None:
                out.append(f"        issue: {e['issue']}")
            out.append(f"        labels: [{', '.join(q(x) for x in e.get('labels', []))}]")
            out.append("        tasks:")
            for t in e["tasks"]:
                fields = [f"issue: {t.get('issue')}", f"title: {q(t['title'])}"]
                if t.get("tags"):
                    fields.append(f"tags: [{', '.join(t['tags'])}]")
                if t.get("spec"):
                    fields.append(f"spec: {q(t['spec'])}")
                fields.append(f"status: {t.get('status', 'open')}")
                out.append(f"          - {{ {', '.join(fields)} }}")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


# ---- generated page


def page_block(data: dict[str, Any]) -> str:
    lines = [
        START,
        "",
        "| Milestone | Gate | Release | Done | Open |",
        "| --- | --- | --- | --- | --- |",
    ]
    for m in data["milestones"]:
        items = [t for e in m["epics"] for t in e["tasks"] if t.get("status") != "dropped"]
        done = sum(t.get("status") == "done" for t in items)
        open_ = len(items) - done
        lines.append(f"| {m['title']} | {m['gate']} | {m['release']} | {done} | {open_} |")
    for m in data["milestones"]:
        lines += ["", f"### {m['title']}", "", f"Gate: {m['gate']}", ""]
        lines += ["| Epic | Task | Issue | Spec | Status |", "| --- | --- | --- | --- | --- |"]
        for e in m["epics"]:
            for t in e["tasks"]:
                spec = f"[{t['spec']}]({SPECS_URL})" if t.get("spec") else ""
                status = {"done": "Done", "dropped": "Dropped"}.get(t.get("status", ""), "Open")
                number = t.get("issue")
                issue = f"[#{number}]({ISSUES_URL}/{number})" if number else "missing"
                cells = [e["title"], t["title"], issue, spec, status]
                lines.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
    lines += ["", END]
    return "\n".join(lines)


def page_with_block(data: dict[str, Any]) -> str:
    text = PAGE.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit(f"{PAGE.relative_to(ROOT)}: generated block markers missing")
    head, rest = text.split(START, 1)
    tail = rest.split(END, 1)[1]
    return head + page_block(data) + tail


def render(data: dict[str, Any]) -> None:
    ROADMAP.write_text(dump(data), encoding="utf-8", newline="\n")
    PAGE.write_text(page_with_block(data), encoding="utf-8", newline="\n")


# ---- offline checks


def problems_of(data: dict[str, Any], pr_body: str | None = None) -> list[str]:
    problems: list[str] = []
    if set(data) != {"labels", "milestones"}:
        problems.append(f"top-level keys must be labels and milestones, not {sorted(data)}")
    seen: dict[int, str] = {}
    status_of: dict[int, str] = {}
    referenced: set[str] = set()
    spec_ids = {p.name[:4] for p in SPECS.glob("[0-9][0-9][0-9][0-9]-*") if p.is_dir()}
    releases = [m.get("release", "") for m in data["milestones"]]
    if not all(SEMVER.match(r) for r in releases):
        problems.append("every milestone needs a release X.Y.Z (the version that ships it)")
    elif [tuple(map(int, r.split("."))) for r in releases] != sorted(
        tuple(map(int, r.split("."))) for r in releases
    ):
        problems.append("milestone releases must not decrease in roadmap order")
    for m in data["milestones"]:
        if set(m) - MILESTONE_KEYS:
            problems.append(f"{m.get('title')}: unknown keys {sorted(set(m) - MILESTONE_KEYS)}")
        for e in m["epics"]:
            if set(e) - EPIC_KEYS:
                problems.append(f"{e.get('title')}: unknown keys {sorted(set(e) - EPIC_KEYS)}")
            numbers = [e.get("issue")] if e.get("issue") is not None else []
            for t in e["tasks"]:
                where = f"{m['title']} / {e['title']} / {t.get('title')}"
                if set(t) - TASK_KEYS:
                    problems.append(f"{where}: unknown keys {sorted(set(t) - TASK_KEYS)}")
                if not isinstance(t.get("issue"), int):
                    problems.append(f"{where}: every task needs an issue number")
                else:
                    numbers.append(t["issue"])
                    status_of[t["issue"]] = t.get("status", "open")
                if t.get("status", "open") not in STATUSES:
                    problems.append(f"{where}: status must be one of {STATUSES}")
                if t.get("spec"):
                    referenced.add(t["spec"])
                    if t["spec"] not in spec_ids:
                        problems.append(f"{where}: spec {t['spec']} does not exist in specs/")
            for n in numbers:
                if n in seen:
                    problems.append(f"issue #{n} appears twice ({seen[n]} and {e['title']})")
                seen[n] = e["title"]
    for spec in sorted(spec_ids - referenced):
        problems.append(f"spec {spec} is not referenced by any roadmap task")
    if ROADMAP.read_text(encoding="utf-8") != dump(data):
        problems.append("roadmap/roadmap.yaml is not in canonical form")
    if PAGE.read_text(encoding="utf-8") != page_with_block(data):
        problems.append("docs/en/project/roadmap.md is not generated from roadmap.yaml")
    if pr_body is not None:
        for n in re.findall(r"(?im)^[ \t]*(?:closes|fixes|resolves)[ \t]+#(\d+)", pr_body):
            if int(n) not in seen:
                problems.append(f"the pull request closes #{n}, which is not in the roadmap")
            elif int(n) in status_of and status_of[int(n)] == "open":
                # Merging closes the issue: the file must say so in the same change, or the
                # roadmap and GitHub differ until another pull request.
                problems.append(f"the pull request closes #{n}: mark its task done here")
    return problems


def check(pr_body_file: Path | None) -> int:
    body = pr_body_file.read_text(encoding="utf-8") if pr_body_file else None
    problems = problems_of(load(), body)
    if problems:
        print("Roadmap problems:\n  " + "\n  ".join(problems))
        print("Fix the file, then run: python scripts/roadmap.py render")
        return 1
    print("Roadmap consistent.")
    return 0


# ---- GitHub


def gh(*args: str, payload: dict[str, Any] | None = None) -> Any:
    cmd = ["gh", "api", *args]
    if payload is not None:
        cmd += ["--input", "-"]
    out = subprocess.run(
        cmd,
        input=json.dumps(payload) if payload is not None else None,
        capture_output=True,
        text=True,
    )
    if out.returncode != 0:
        sys.exit(f"gh api {' '.join(args)} failed: {out.stderr.strip()}")
    return json.loads(out.stdout) if out.stdout.strip() else None


def github_issues() -> dict[int, dict[str, Any]]:
    # Explicit pages: `--paginate` follows links of the form repositories/<id>/..., which some
    # proxies refuse; the page parameter works everywhere.
    out: dict[int, dict[str, Any]] = {}
    page = 1
    while True:
        batch = gh(f"repos/{REPO}/issues?state=all&per_page=100&page={page}")
        out.update({i["number"]: i for i in batch if "pull_request" not in i})
        if len(batch) < 100:
            return out
        page += 1


def github_milestones() -> dict[str, int]:
    return {m["title"]: m["number"] for m in gh(f"repos/{REPO}/milestones?state=all&per_page=100")}


def sync(write: bool, apply_milestones: bool) -> int:
    data = load()
    issues = github_issues()
    milestones = github_milestones()
    planned: set[int] = set()
    drift: list[str] = []
    for m, _epic, t in tasks(data):
        planned.add(t["issue"])
        issue = issues.get(t["issue"])
        if issue is None:
            drift.append(f"#{t['issue']} ({t['title']}): no such issue on GitHub")
            continue
        state = "open"
        if issue["state"] == "closed":
            state = "dropped" if issue.get("state_reason") == "not_planned" else "done"
        if t.get("status", "open") != state:
            drift.append(f"#{t['issue']}: status {t.get('status', 'open')} here, {state} on GitHub")
            t["status"] = state
        on_github = (issue.get("milestone") or {}).get("title")
        if on_github != m["title"]:
            drift.append(f"#{t['issue']}: milestone '{on_github}' on GitHub, '{m['title']}' here")
            if apply_milestones:
                if m["title"] not in milestones:
                    sys.exit(f"milestone '{m['title']}' does not exist on GitHub")
                gh(
                    "-X",
                    "PATCH",
                    f"repos/{REPO}/issues/{t['issue']}",
                    payload={"milestone": milestones[m["title"]]},
                )
    for e in (e for m in data["milestones"] for e in m["epics"]):
        if e.get("issue") is not None:
            planned.add(e["issue"])
    untriaged = []
    for n, issue in sorted(issues.items()):
        if n in planned or issue["state"] != "open":
            continue
        title = json.dumps(issue["title"], ensure_ascii=False)
        if issue.get("milestone"):
            drift.append(f"#{n} {title}: in a milestone on GitHub but not in the roadmap")
        else:
            # Reports from users: triage decides whether they enter the roadmap.
            untriaged.append(f"#{n} {title}")
    if untriaged:
        print(
            "Open issues not yet triaged into the roadmap (warning):\n  " + "\n  ".join(untriaged)
        )
    if write:
        render(data)
    if drift:
        print("Roadmap and GitHub differ:\n  " + "\n  ".join(drift))
        if write or apply_milestones:
            print("Statuses written to the file." if write else "")
            return 0
        print("Run: python scripts/roadmap.py sync --write [--apply-milestones]")
        return 1
    print("Roadmap and GitHub agree.")
    return 0


def list_tasks(only_open: bool, milestone: str | None) -> int:
    for m, e, t in tasks(load()):
        if milestone and not m["title"].startswith(milestone):
            continue
        if only_open and t.get("status", "open") != "open":
            continue
        spec = f" [SPEC-{t['spec']}]" if t.get("spec") else ""
        status = t.get("status", "open")
        print(f"#{t['issue']:<4} {status:<7} {m['title'][:2]} / {e['title']}: {t['title']}{spec}")
    return 0


def new_issue(args: argparse.Namespace) -> int:
    data = load()
    milestone = next((m for m in data["milestones"] if m["title"].startswith(args.milestone)), None)
    if milestone is None:
        sys.exit(f"no milestone starts with '{args.milestone}'")
    epic = next((e for e in milestone["epics"] if e["title"] == args.epic), None)
    if epic is None:
        epic = {"title": args.epic, "labels": [], "tasks": []}
        milestone["epics"].append(epic)
    labels = [x for x in (args.labels or "").split(",") if x]
    numbers = github_milestones()
    if milestone["title"] not in numbers:
        sys.exit(f"milestone '{milestone['title']}' does not exist on GitHub")
    body = args.body.read_text(encoding="utf-8") if args.body else ""
    if epic.get("issue"):
        body = f"Part of #{epic['issue']}.\n\n{body}".strip()
    created = gh(
        "-X",
        "POST",
        f"repos/{REPO}/issues",
        payload={
            "title": args.title,
            "body": body,
            "milestone": numbers[milestone["title"]],
            "labels": sorted(set(labels) | set(epic.get("labels", []))),
        },
    )
    task: dict[str, Any] = {"issue": created["number"], "title": args.title, "status": "open"}
    if args.spec:
        task["spec"] = args.spec
    tags = [x for x in labels if x in {"parallel", "maintainer", "needs-methodology"}]
    if tags:
        task["tags"] = tags
    epic["tasks"].append(task)
    render(data)
    print(f"#{created['number']} created in {milestone['title']} / {epic['title']}")
    return 0


def main() -> None:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    sub = parser.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("check")
    c.add_argument("--pr-body", type=Path)
    sub.add_parser("render")
    li = sub.add_parser("list")
    li.add_argument("--open", action="store_true")
    li.add_argument("--milestone")
    s = sub.add_parser("sync")
    s.add_argument("--write", action="store_true")
    s.add_argument("--apply-milestones", action="store_true")
    n = sub.add_parser("new")
    n.add_argument("--milestone", required=True, help="prefix, for example M2")
    n.add_argument("--epic", required=True)
    n.add_argument("--title", required=True)
    n.add_argument("--labels")
    n.add_argument("--spec")
    n.add_argument("--body", type=Path)
    args = parser.parse_args()
    if args.cmd == "check":
        sys.exit(check(args.pr_body))
    if args.cmd == "list":
        sys.exit(list_tasks(args.open, args.milestone))
    if args.cmd == "render":
        render(load())
        return
    if args.cmd == "sync":
        sys.exit(sync(args.write, args.apply_milestones))
    sys.exit(new_issue(args))


if __name__ == "__main__":
    main()
